const target = path.join(root, 'middleware/node-red/flows.json');
const json = JSON.stringify(flows, null, 4) + '\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== json) {
    console.error('flows.json is out of date: run node scripts/build-flows.js');
    process.exit(1);
  }
  console.log('flows.json is up to date');
} else {
  fs.writeFileSync(target, json);
  console.log(`Wrote ${flows.length} nodes to ${path.relative(root, target)}`);
}
