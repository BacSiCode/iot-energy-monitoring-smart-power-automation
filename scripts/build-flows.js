// Generates middleware/node-red/flows.json from the readable sources in
// middleware/node-red/src. Run: node scripts/build-flows.js
// Use --check to fail if flows.json is out of date (used by tests).
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = (name) => fs.readFileSync(path.join(root, 'middleware/node-red/src', name), 'utf8').replace(/\r\n/g, '\n');
